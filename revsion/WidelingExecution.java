package TypeCastingExecution;

public class WidelingExecution {
	public static void main(String[] args) {
		int a=10;
		double d=a;
		System.out.println("Smallest Value :- "+a);
		System.out.println("Largest Value :-"+d);
		
		System.out.println("-----------------------------------------------");
		char ch='S';
		double d1=ch;
		System.out.println("Smallest Value :-" +ch);
		System.out.println("Largest Value :-"+d1 );
	}

}

