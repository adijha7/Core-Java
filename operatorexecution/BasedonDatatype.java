package operatorexecution;

public class BasedonDatatype {
    public static void main(String[] args) {
		
		// Primitive Variable declaration and in
		int a=10;
		System.out.println(a);
		
		// non Primitive Variable declaration and in
		BasedonDatatype b=null;
		System.out.println(b);
		
		String s=null;
		System.out.println(s);
		
		double d=0.0d;
		System.out.println(d);
		
		
	}
    
}
